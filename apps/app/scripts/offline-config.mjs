// Writes wrangler.offline.jsonc: the Worker's config with every binding that needs a Cloudflare
// account removed, so `pnpm dev` runs on Miniflare alone, with no login. Without the Images
// binding the Worker stores no images at all: avatars are initials and images are links. It
// never falls back to decoding images on this machine.
import { readFileSync, writeFileSync } from 'node:fs'

const src = new URL('../wrangler.jsonc', import.meta.url)
const out = new URL('../wrangler.offline.jsonc', import.meta.url)

// wrangler.jsonc uses whole-line `//` comments only, so dropping those lines leaves JSON.
const text = readFileSync(src, 'utf8').split('\n').filter(l => !/^\s*\/\//.test(l)).join('\n')
let config
try {
  config = JSON.parse(text)
} catch (e) {
  console.error(`offline-config: wrangler.jsonc must stay JSON with whole-line comments only (${e.message})`)
  process.exit(1)
}
delete config.images
writeFileSync(out, `// Generated by scripts/offline-config.mjs for \`pnpm dev\`; edit wrangler.jsonc instead.\n${JSON.stringify(config, null, 2)}\n`)
console.log('offline-config: images off for local dev (no Cloudflare account needed)')
